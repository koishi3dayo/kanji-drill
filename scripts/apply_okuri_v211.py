def apply_to(fname, fixes, alt=False):
    path = BASE / fname
    src = path.read_text(encoding='utf-8')
    applied, missing = [], []

    for kanji, old_tpl, old_rd, new_tpl, new_rd in fixes:
        if alt:
            old_line = '"%s":{tpl:"%s",reading:"%s",' % (kanji, old_tpl, old_rd)
            new_line = '"%s":{tpl:"%s",reading:"%s",' % (kanji, new_tpl, new_rd)
        else:
            old_line = '"%s":[{tpl:"%s",reading:"%s",' % (kanji, old_tpl, old_rd)
            new_line = '"%s":[{tpl:"%s",reading:"%s",' % (kanji, new_tpl, new_rd)

        cnt = src.count(old_line)
        if cnt == 1:
            src = src.replace(old_line, new_line)
            applied.append((kanji, old_tpl, new_tpl, new_rd))
        else:
            missing.append((kanji, old_tpl, cnt))

    print(f"\n=== {fname} ===")
    print(f"適用: {len(applied)}件 / 不一致(要確認): {len(missing)}件")
    for kanji, old_tpl, new_tpl, new_rd in applied:
        print(f"  {kanji}: {old_tpl} -> {new_tpl} (reading:{new_rd})")
    for kanji, old_tpl, cnt in missing:
        print(f"  !! {kanji}: 一致0件または複数({cnt}) -> {old_tpl}")

    if '--apply' in sys.argv and not missing:
        path.write_text(src, encoding='utf-8')
        print(f">>> {fname} に{len(applied)}件を反映しました。")
    elif '--apply' in sys.argv:
        print(f">>> 不一致があるため {fname} は書き換えていません。")
    return len(missing)


if __name__ == '__main__':
    bad = apply_to('sentence-data.js', FIXES_MAIN, alt=False)
    bad += apply_to('sentence-data-alt.js', FIXES_ALT, alt=True)
    if '--apply' not in sys.argv:
        print("\n(レポートのみ。反映するには --apply を付けて再実行)")
    sys.exit(1 if bad else 0)
